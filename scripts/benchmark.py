"""Measure the pipeline's own performance and accuracy. Uses THROWAWAY schemas in the Postgres named by TEST_DATABASE_URL (dropped on exit).

Run from the project root:   python scripts/benchmark.py
Measures: per-stage latency, sequential vs parallel throughput, extraction accuracy against known ground truth,
score repeatability, and chat latency. Live LLM calls are used, so it takes several minutes.
"""
import json
import os
import re
import statistics
import sys
import tempfile
import time
from collections import defaultdict
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TMP = Path(tempfile.mkdtemp(prefix="shortlist_bench_"))
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))
from pg_scratch import switch_to_new_scratch_schema, use_scratch_schema  # noqa: E402

use_scratch_schema("bench")                                    # must happen before app.config is imported

from app.database import get_connection, init_db  # noqa: E402
from app.llm import query_engine  # noqa: E402
from app.llm.scoring import _canon, score_candidate  # noqa: E402
from app.llm.verification import skill_in_text  # noqa: E402
from app.models import CandidateProfile  # noqa: E402
from app.services import candidate_service as svc  # noqa: E402
from app.services.skill_normalizer import load_aliases  # noqa: E402

SAMPLES = ROOT / "data" / "sample_resumes"
FILES = ["jeevan_raj.pdf", "anurag_aiml.pdf", "ananya_rk_testing.pdf", "kushal_br.pdf", "anurag_ibm_swe.docx",
         "synthetic_priya_sharma.pdf", "synthetic_rahul_verma.pdf", "synthetic_ananya_iyer.pdf"]
# Ground truth (known because the synthetic resumes are generated by tests/make_samples.py; real ones are fresher resumes).
YEARS = {"jeevan_raj.pdf": 0, "anurag_aiml.pdf": 0, "ananya_rk_testing.pdf": 0, "kushal_br.pdf": 0, "anurag_ibm_swe.docx": 0,
         "synthetic_priya_sharma.pdf": 4, "synthetic_rahul_verma.pdf": 2, "synthetic_ananya_iyer.pdf": 0}
SKILLS_TRUTH = {
    "synthetic_priya_sharma.pdf": ["Python", "FastAPI", "TensorFlow", "Machine Learning", "Docker", "PostgreSQL", "Git"],
    "synthetic_rahul_verma.pdf": ["Java", "Spring Boot", "MySQL", "Python", "SQL"],
    "synthetic_ananya_iyer.pdf": ["Python", "Pandas", "Scikit-learn", "SQL", "Deep Learning"],
}

# ---- per-stage timers: wrap the pipeline's collaborators without changing them ----
cur: dict = {}


def timed(label, fn):
    def wrapper(*a, **k):
        t = time.perf_counter()
        try:
            return fn(*a, **k)
        finally:
            cur[label] = cur.get(label, 0.0) + (time.perf_counter() - t)
    return wrapper


for label, name in [("1 text extraction", "extract_document"), ("2 AI extraction", "extract_profile"), ("3 verification", "verify_profile"),
                    ("4 skill normalisation", "canonicalize_profile"), ("5 scoring", "score_candidate")]:
    setattr(svc, name, timed(label, getattr(svc, name)))


def pct(vals, p):
    vals = sorted(vals)
    return vals[min(len(vals) - 1, int(round(p / 100 * (len(vals) - 1))))]


init_db()
conn = get_connection()
jd = (ROOT / "data" / "sample_job_description.txt").read_text(encoding="utf-8")
t0 = time.perf_counter()
job_id, msg = svc.create_job(conn, jd)
jd_seconds = time.perf_counter() - t0
print(f"job created in {jd_seconds:.1f}s: {msg}", flush=True)

# ---------------------------------------------------------------- A. sequential run with stage timing
stages: dict[str, list[float]] = defaultdict(list)
totals, statuses = [], {}
seq_start = time.perf_counter()
for fn in FILES:
    cur.clear()
    t = time.perf_counter()
    o = svc.process_resume(conn, (SAMPLES / fn).read_bytes(), fn, job_id)
    total = time.perf_counter() - t
    totals.append(total); statuses[fn] = o.status
    for k, v in cur.items():
        stages[k].append(v)
    stages["6 database write + dedupe"].append(max(0.0, total - sum(cur.values())))
    print(f"  {fn:30} {o.status:10} {o.score if o.score is not None else '-':>6} {total:5.1f}s", flush=True)
seq_wall = time.perf_counter() - seq_start
ok_seq = sum(s == "stored" for s in statuses.values())

# ---------------------------------------------------------------- B. accuracy on verifiable facts
rows = conn.execute("""SELECT a.id, a.resume_filename f, a.raw_text, a.experience_years, c.name, c.email
                       FROM applications a JOIN candidates c ON c.id=a.candidate_id WHERE a.application_status='active'""").fetchall()
aliases = load_aliases(conn)
email_ok = name_ok = years_ok = 0
grounded = total_skills = 0
for r in rows:
    emails = {e.lower() for e in re.findall(r"[\w.+-]+@[\w-]+\.[\w.-]+", r["raw_text"])}
    email_ok += bool(r["email"]) and r["email"].lower() in emails
    first = (r["name"] or "").split()[0].lower() if r["name"] else ""
    name_ok += bool(first) and first in r["raw_text"].lower()[:400]
    years_ok += (r["experience_years"] or 0) == YEARS.get(r["f"], -1)
    for s in conn.execute("SELECT raw_skill, skill_name FROM application_skills WHERE application_id=?", (r["id"],)):
        total_skills += 1
        grounded += skill_in_text(s["raw_skill"] or s["skill_name"], r["raw_text"], aliases)
removed = conn.execute("SELECT COUNT(*) FROM verification_log WHERE evidence_quote LIKE '[deterministic] skill not present%'").fetchone()[0]
moved = conn.execute("SELECT COUNT(*) FROM verification_log WHERE evidence_quote LIKE '[deterministic] moved to soft%'").fetchone()[0]
llm_fixes = conn.execute("SELECT COUNT(*) FROM verification_log WHERE evidence_quote LIKE '[llm]%'").fetchone()[0]

tp = fp = fn_ = 0
per_file_pr = {}
for f, truth in SKILLS_TRUTH.items():
    row = next((r for r in rows if r["f"] == f), None)
    if not row:
        continue
    got = {_canon(s["skill_name"], aliases) for s in conn.execute("SELECT skill_name FROM application_skills WHERE application_id=?", (row["id"],))}
    want = {_canon(s, aliases) for s in truth}
    t_, f_, n_ = len(got & want), len(got - want), len(want - got)
    tp += t_; fp += f_; fn_ += n_
    per_file_pr[f] = {"found": sorted(got), "missed": sorted(want - got), "extra": sorted(got - want)}
precision = tp / (tp + fp) if tp + fp else 0
recall = tp / (tp + fn_) if tp + fn_ else 0

# ---------------------------------------------------------------- C. score repeatability (same stored profile, scored 3 times)
spread = []
for r in rows[:5]:
    prof = CandidateProfile.model_validate_json(conn.execute("SELECT profile_json FROM applications WHERE id=?", (r["id"],)).fetchone()[0])
    job = svc.get_job(conn, job_id)
    base = conn.execute("SELECT match_score FROM analysis_results WHERE application_id=?", (r["id"],)).fetchone()[0]
    runs = [base] + [score_candidate(prof, job, aliases).match_score for _ in range(2)]
    spread.append(max(runs) - min(runs))
    print(f"  repeat {r['f']:28} {runs}", flush=True)

# ---------------------------------------------------------------- D. parallel throughput (fresh DB, 4 workers)
import app.config as cfg  # noqa: E402
import app.database as dbm  # noqa: E402
switch_to_new_scratch_schema("bench_par")
dbm.init_db()
pconn = dbm.get_connection()
pjob, _ = svc.create_job(pconn, jd)


def worker(fn):
    c = dbm.get_connection()
    try:
        return fn, svc.process_resume(c, (SAMPLES / fn).read_bytes(), fn, pjob).status
    finally:
        c.close()


par_start = time.perf_counter()
with ThreadPoolExecutor(max_workers=4) as pool:
    par = list(pool.map(worker, FILES))
par_wall = time.perf_counter() - par_start
ok_par = sum(s == "stored" for _, s in par)

# ---------------------------------------------------------------- E. chat latency
chat_times = []
for q in ["Show me the top 5 candidates.", "Which candidates know Python?", "Which candidates are missing Docker?",
          "Why is Jeevan ranked higher than Priya?", "Show candidates with more than 2 years of experience."]:
    t = time.perf_counter()
    query_engine.ask(conn, job_id, q, remember=False)
    chat_times.append(time.perf_counter() - t)

# ---------------------------------------------------------------- report
res = {
    "resumes": len(FILES), "job_parse_s": round(jd_seconds, 1),
    "sequential": {"wall_s": round(seq_wall, 1), "stored": ok_seq, "per_resume_mean_s": round(statistics.mean(totals), 1),
                   "p50_s": round(pct(totals, 50), 1), "p95_s": round(pct(totals, 95), 1),
                   "resumes_per_minute": round(len(FILES) / seq_wall * 60, 1)},
    "stage_mean_s": {k: round(statistics.mean(v), 2) for k, v in sorted(stages.items())},
    "parallel_4_workers": {"wall_s": round(par_wall, 1), "stored": ok_par, "resumes_per_minute": round(len(FILES) / par_wall * 60, 1),
                           "speedup": round(seq_wall / par_wall, 2), "statuses": [s for _, s in par]},
    "accuracy": {"email_exact": f"{email_ok}/{len(rows)}", "name_found_in_header": f"{name_ok}/{len(rows)}",
                 "experience_years_exact": f"{years_ok}/{len(rows)}",
                 "skills_grounded_in_resume_text": f"{grounded}/{total_skills}",
                 "hallucinated_skills_removed_by_check": removed, "soft_skills_moved": moved, "second_ai_corrections": llm_fixes,
                 "synthetic_skill_precision": round(precision, 3), "synthetic_skill_recall": round(recall, 3), "per_file": per_file_pr},
    "score_repeatability": {"max_spread_points_per_candidate": [round(s, 1) for s in spread], "worst": round(max(spread), 1)},
    "chat_latency_s": {"mean": round(statistics.mean(chat_times), 1), "max": round(max(chat_times), 1), "each": [round(t, 1) for t in chat_times]},
}
out = TMP / "results.json"
out.write_text(json.dumps(res, indent=2), encoding="utf-8")
print("\n=== RESULTS ===")
print(json.dumps(res, indent=2))
print("\nresults saved to", out)
