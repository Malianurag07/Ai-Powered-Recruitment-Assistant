def test_columns_keep_their_required_and_default_settings():
    """Replaces the SQLite parity check for nullability and defaults: the facts were verified against the live database file, then pinned."""
    actual = {(tb, col, c["notnull"], c["default"]) for tb, info in SCH.items() for col, c in info["cols"].items()}
    assert actual == set(PINNED_COLUMNS), {"changed_or_new": sorted(actual - set(PINNED_COLUMNS)), "lost": sorted(set(PINNED_COLUMNS) - actual)}
    assert len(PINNED_COLUMNS) == 91          # the live file had 12 tables and 91 columns, all present


